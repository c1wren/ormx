-- Schema for the existing CRUD example; use only in a disposable database.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE clubs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    test1 text NOT NULL,
    test2 integer NOT NULL,
    test3 boolean DEFAULT true,
    test4 integer[],
    type integer NOT NULL,
    encrypted bytea NOT NULL
);

CREATE TABLE composite (
    name text NOT NULL,
    other text NOT NULL,
    non_key text NOT NULL,
    PRIMARY KEY (name, other)
);

CREATE TABLE all_keys (
    value text NOT NULL,
    field text NOT NULL,
    PRIMARY KEY (value, field)
);

CREATE TABLE mostly_keys (
    value text NOT NULL,
    field text NOT NULL,
    other text NOT NULL,
    PRIMARY KEY (value, field)
);
